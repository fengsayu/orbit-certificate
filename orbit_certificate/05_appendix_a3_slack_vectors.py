# I_28 is the 28-by-28 identity matrix, not a vector.
I_28 = [[1 if i == j else 0 for j in range(28)] for i in range(28)]


def matrix_vector_product(matrix, vector):
    """Multiply a matrix by a column vector using exact integer arithmetic."""
    return [
        sum(row[j] * vector[j] for j in range(len(vector)))
        for row in matrix
    ]


def compute_slack_vectors():
    """Compute u = Q^T alpha + beta - 64 e_0 and its companion v."""
    if len(Q) != 28 or any(len(row) != 28 for row in Q):
        raise ValueError("Q must be a 28-by-28 matrix.")
    if any(len(vector) != 28 for vector in (alpha, beta, e_0)):
        raise ValueError("Every vector must have 28 entries.")

    Q_T = [list(column) for column in zip(*Q)]
    two_Q_T_plus_I = [
        [2 * Q_T[i][j] + I_28[i][j] for j in range(28)]
        for i in range(28)
    ]

    # Compute u = Q^T alpha + beta - 64 e_0.
    Q_T_alpha = matrix_vector_product(Q_T, alpha)
    u = [Q_T_alpha[i] + beta[i] - 64 * e_0[i] for i in range(28)]

    # Compute v = (2 Q^T + I_28) alpha + beta - 128 e_0.
    second_product = matrix_vector_product(two_Q_T_plus_I, alpha)
    v = [second_product[i] + beta[i] - 128 * e_0[i] for i in range(28)]
    return u, v


